const KEYS = Object.keys(PARASHA_HUES).sort((a, b) => b.length - a.length);

/**
 * הגוון של פרשה. פרשות מחוברות (למשל 'vayakhel-pekudei') מקבלות את צבע הפרשה הראשונה.
 * מזהה לא מוכר → undefined (והממשק נשאר עם צבע ברירת המחדל).
 */
export function parashaHue(id: string | undefined | null): ParashaHue | undefined {
  if (!id) return undefined;
  if (PARASHA_HUES[id]) return PARASHA_HUES[id];
  const first = KEYS.find((k) => id.startsWith(k + '-'));
  return first ? PARASHA_HUES[first] : undefined;
}

/** חמשת החומשים לפי סדר — למקרא הצבעים */
export const PARASHA_BOOKS: readonly { name: string; ids: readonly string[] }[] = (() => {
  const ids = Object.keys(PARASHA_HUES);
  const cut = [
    ['ספר בראשית', 0, 12],
    ['ספר שמות', 12, 23],
    ['ספר ויקרא', 23, 33],
    ['ספר במדבר', 33, 43],
    ['ספר דברים', 43, 54],
  ] as const;
  return cut.map(([name, a, b]) => ({ name, ids: ids.slice(a, b) }));
})();

/** האם מזהה פרשה (גם מחוברת, למשל 'vayakhel-pekudei') כולל את הפרשה key */
export function parashaIncludes(id: string | undefined | null, key: string): boolean {
  if (!id) return false;
  return id === key || id.startsWith(key + '-') || id.endsWith('-' + key);
}
